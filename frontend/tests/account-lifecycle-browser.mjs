    await expect(dialog).toContainText('成功 1 · 失败 0')
    const syncCalls = calls.filter(call => call.path === '/api/accounts/sync/crs')
    assert.deepEqual(syncCalls[0].body, syncCalls[1].body)
    assert.deepEqual(syncCalls[0].body.selected_account_ids, ['crs-ready'])
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    assertions.push('CRS纯预览、HTTP显式选择、密码不展示、无效项禁选、冻结相同同步重试')
    listRows = Array.from({ length: 23 }, (_, index) => account(`batch-${index}`, `批量额度合成账号 ${index}`, { version: 3 }))
    await page.getByRole('button', { name: '刷新账号列表', exact: true }).click()
    await expect(page.locator('.account-directory-heading')).toContainText('共 23 个')
