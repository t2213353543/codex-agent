    await page.getByRole('button', { name: '刷新账号列表', exact: true }).click()
    await expect.poll(() => calls.filter(call => call.path === '/api/accounts/manage' && call.headers['if-none-match']).length).toBeGreaterThan(0)
    await expect(page.locator('.accounts-panel')).toContainText(row.name)
    assertions.push('账号条件刷新发送内存ETag，304保留原列表与精确总数')
    await tick(page.getByRole('checkbox', { name: '今日用量', exact: true }))
    await expect(page.locator('.accounts-panel')).toContainText('Token')
    await expect(page.locator('.accounts-panel')).not.toContainText('费用未定价')
    const today = calls.find(call => call.path === '/api/accounts/usage-batch').body
    assert.deepEqual(today.ids, [row.id]); assert.ok(today.to > today.from && today.to - today.from <= 90000)
    assert.equal(new Date(today.from * 1000).getHours(), 0)
    assertions.push('今日批量统计传稳定ID和明确本地零点区间，仅显示请求与Token用量')
    await tick(page.getByRole('checkbox', { name: '今日用量', exact: true }))
    await page.getByRole('button', { name: `查看账号 ${row.name} 详情`, exact: true }).click()
    const details = page.getByRole('dialog', { name: '账号详情', exact: true })
    await expect(details.locator('.identity-panel')).toContainText('synthetic@example.test')
    await expect(details.locator('.identity-panel')).toContainText('workspace-fixture')
    await expect(details.locator('.identity-panel')).toContainText('声明未经远端验证')
    assertions.push('身份邮箱/workspace/user/agent来源只读展示，未验证JWT声明不冒充实时套餐权限')
    await details.getByRole('button', { name: '定时检查', exact: true }).click()
    let dialog = page.getByRole('dialog', { name: '定时检查与测试', exact: true })
    await expect(dialog).toContainText('还没有定时计划')
    await dialog.getByRole('button', { name: '创建计划', exact: true }).click()
    await select('计划检查类型', '普通流式推理', dialog)
    await dialog.getByRole('textbox', { name: '计划模型 ID', exact: true }).fill('gpt-codex-fixture')
    await dialog.getByRole('button', { name: '保存计划', exact: true }).click()
    await expect(dialog).toContainText('启用推理计划前请确认')
    assert.equal(calls.filter(call => call.path.endsWith('/schedules') && call.method === 'POST').length, 0)
    await tick(dialog.getByRole('checkbox', { name: '我确认此计划会周期性发送推理请求，可能消耗上游额度', exact: true }))
    await dialog.getByRole('button', { name: '保存计划', exact: true }).click()
    await expect(dialog.locator('.schedule-plan')).toHaveCount(1)
    assert.equal(calls.filter(call => call.path.endsWith('/schedules') && call.method === 'POST')[0].body.confirm_inference, true)
    await dialog.getByRole('button', { name: '编辑', exact: true }).click()
    conflictPlan = true
    await dialog.getByRole('textbox', { name: '计划 Cron', exact: true }).fill('*/15 * * * *')
    await tick(dialog.getByRole('checkbox', { name: '我确认此计划会周期性发送推理请求，可能消耗上游额度', exact: true }))
    await dialog.getByRole('button', { name: '保存计划', exact: true }).click()
    await expect(dialog).toContainText('当前输入已保留')
    await expect(dialog.getByRole('textbox', { name: '计划 Cron', exact: true })).toHaveValue('*/15 * * * *')
    conflictPlan = false
    await dialog.getByRole('button', { name: '取消编辑', exact: true }).click()
    await dialog.getByRole('button', { name: '运行历史', exact: true }).click()
    await expect(dialog.locator('.schedule-history details')).toContainText('结果未知')
    await capture('account-schedules-1440')
    await page.setViewportSize({ width: 320, height: 900 })
    assert.ok(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1))
    await capture('account-schedules-320')
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    assertions.push('计划显式推理确认、创建、版本冲突保留输入、unknown运行历史及320px')
    await details.getByRole('button', { name: '账号到期管理', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '账号到期管理', exact: true })
    await dialog.getByLabel('账号租期到期时间', { exact: true }).fill('2027-01-02T03:04')
    conflictLease = true
    await dialog.getByRole('button', { name: '保存租期', exact: true }).click()
    await expect(dialog).toContainText('当前输入已保留')
    await expect(dialog.getByLabel('账号租期到期时间', { exact: true })).toHaveValue('2027-01-02T03:04')
    conflictLease = false
    await dialog.getByRole('button', { name: '保存租期', exact: true }).click()
    await expect(dialog).toContainText('账号租期已保存')
    await expect(dialog).toContainText('账号已在自动停用后发生变化')
    const leaseBody = calls.filter(call => call.path.endsWith('/lease') && call.method === 'PUT').at(-1).body
    assert.equal(leaseBody.account_version, 11); assert.equal(leaseBody.version, 0); assert.ok(Number.isSafeInteger(leaseBody.expires_at))
    await dialog.getByRole('button', { name: '关闭', exact: true }).click()
    assertions.push('独立租期双版本保护、冲突不丢输入、安全恢复跳过原因及Unix秒')
    await details.getByRole('button', { name: '账号统计', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '账号使用统计', exact: true })
    await expect(dialog).toContainText('1234')
    await expect(dialog).not.toContainText('未定价')
    await expect(dialog).toContainText('无采集样本')
    await expect(dialog.locator('.account-sales-estimate')).toHaveCount(0)
    await expect(dialog).toContainText('日均请求')
    await capture('account-statistics-1440')
    unknownSales = true
    await dialog.getByRole('button', { name: '今天', exact: true }).click()
    await expect.poll(() => calls.filter(call => call.path === '/api/logs/stats').length).toBe(2)
    await expect(dialog.getByRole('button', { name: '查询统计', exact: true })).not.toHaveClass(/is-loading/)
    await expect(dialog.locator('.account-sales-estimate')).toHaveCount(0)
    const applied = calls.filter(call => call.path === '/api/logs/stats').at(-1).query
    assert.equal(applied.step, '86400'); assert.equal(applied.as_of, 'lifecycle-daily-snapshot'); assert.ok(applied.timezone)
    await dialog.getByRole('button', { name: '查看该区间使用记录', exact: true }).click()
    await expect(page).toHaveURL(/#\/logs\?/)
    const query = new URLSearchParams(new URL(page.url()).hash.split('?')[1])
    assert.equal(query.get('account_id'), row.id); assert.equal(query.get('from'), applied.from); assert.equal(query.get('to'), applied.to)
    assert.equal(query.has('as_of'), false); assert.equal(query.get('timezone'), applied.timezone)
    assertions.push('账号统计仅请求/Token与时延、日均/峰值、TTFT未知、今日切换与区间深链')
    await page.goto(origin + '/#/accounts')
    await page.getByRole('button', { name: '迁移备份', exact: true }).click()
    await page.getByRole('menuitem', { name: '从 CRS 同步', exact: true }).click()
    dialog = page.getByRole('dialog', { name: '从 CRS 同步 Codex 账号', exact: true })
    await dialog.getByRole('textbox', { name: 'CRS 地址', exact: true }).fill('http://crs.example.test')
    await dialog.getByRole('textbox', { name: 'CRS 用户名', exact: true }).fill('synthetic-user')
    await dialog.getByLabel('CRS 密码', { exact: true }).fill('synthetic-crs-password')
    await dialog.getByRole('button', { name: '连接并预览', exact: true }).click()
    await expect(dialog).toContainText('必须明确勾选')
    assert.equal(calls.filter(call => call.path.endsWith('/crs/preview')).length, 0)
    await dialog.getByRole('textbox', { name: 'CRS 地址', exact: true }).fill('https://crs.example.test')
    await dialog.getByRole('button', { name: '连接并预览', exact: true }).click()
    await expect(dialog).toContainText('来源合成账号')
    assert.ok(!(await dialog.innerText()).includes('synthetic-crs-password'))
    await expect(dialog.getByRole('checkbox', { name: '同步 来源无效账号', exact: true })).toBeDisabled()
    await capture('account-crs-1440')
    await tick(dialog.getByRole('checkbox', { name: '同步 来源合成账号', exact: true }))
    await dialog.getByRole('button', { name: '确认同步 1 个账号', exact: true }).click()
    await expect(dialog.getByRole('checkbox', { name: '同步 来源合成账号', exact: true })).toBeDisabled()
