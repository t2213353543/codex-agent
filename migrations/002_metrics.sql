-- Durable events are retained independently from the detailed request log.
-- Aggregates can always be rebuilt from usage_events. Account deletion never
-- removes a historical event or its stable account reference/name snapshot.
CREATE TABLE IF NOT EXISTS usage_events (
    event_id text PRIMARY KEY,
    created_at timestamptz NOT NULL,
    account_ref text NOT NULL DEFAULT '',
    account_name text NOT NULL DEFAULT '',
    key_id text NOT NULL DEFAULT '',
    status text NOT NULL,
    input_tokens bigint NOT NULL DEFAULT 0,
    output_tokens bigint NOT NULL DEFAULT 0,
    cached_tokens bigint NOT NULL DEFAULT 0,
    latency_ms bigint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS usage_events_time_idx ON usage_events(created_at, event_id);

CREATE TABLE IF NOT EXISTS request_logs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id text NOT NULL UNIQUE REFERENCES usage_events(event_id),
    account_id text REFERENCES accounts(id) ON DELETE SET NULL,
    account_ref text NOT NULL DEFAULT '',
    account_name text NOT NULL DEFAULT '',
    created_at timestamptz NOT NULL,
    status text NOT NULL,
    model text NOT NULL DEFAULT '',
    key_name text NOT NULL DEFAULT '',
    record jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS request_logs_time_idx ON request_logs(created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS request_logs_account_time_idx ON request_logs(account_ref, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS request_logs_name_time_idx ON request_logs(account_name, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS request_logs_errors_time_idx ON request_logs(created_at DESC, id DESC) WHERE status <> 'ok';

CREATE TABLE IF NOT EXISTS usage_minute (
    bucket bigint NOT NULL,
    account_ref text NOT NULL,
    account_name text NOT NULL DEFAULT '',
    requests bigint NOT NULL DEFAULT 0,
    ok bigint NOT NULL DEFAULT 0,
    errors bigint NOT NULL DEFAULT 0,
    tokens bigint NOT NULL DEFAULT 0,
    input bigint NOT NULL DEFAULT 0,
    output bigint NOT NULL DEFAULT 0,
    cached bigint NOT NULL DEFAULT 0,
    latency bigint NOT NULL DEFAULT 0,
    latency_n bigint NOT NULL DEFAULT 0,
    PRIMARY KEY(bucket, account_ref)
);
CREATE INDEX IF NOT EXISTS usage_minute_account_idx ON usage_minute(account_ref, bucket);

CREATE TABLE IF NOT EXISTS usage_daily (
    bucket bigint NOT NULL,
    account_ref text NOT NULL,
    account_name text NOT NULL DEFAULT '',
    requests bigint NOT NULL DEFAULT 0,
    ok bigint NOT NULL DEFAULT 0,
    errors bigint NOT NULL DEFAULT 0,
    tokens bigint NOT NULL DEFAULT 0,
    input bigint NOT NULL DEFAULT 0,
    output bigint NOT NULL DEFAULT 0,
    cached bigint NOT NULL DEFAULT 0,
    latency bigint NOT NULL DEFAULT 0,
    latency_n bigint NOT NULL DEFAULT 0,
    PRIMARY KEY(bucket, account_ref)
);
CREATE INDEX IF NOT EXISTS usage_daily_account_idx ON usage_daily(account_ref, bucket);

CREATE TABLE IF NOT EXISTS usage_totals (
    scope text NOT NULL,
    subject text NOT NULL,
    requests bigint NOT NULL DEFAULT 0,
    ok bigint NOT NULL DEFAULT 0,
    errors bigint NOT NULL DEFAULT 0,
    tokens bigint NOT NULL DEFAULT 0,
    input bigint NOT NULL DEFAULT 0,
    output bigint NOT NULL DEFAULT 0,
    cached bigint NOT NULL DEFAULT 0,
    latency bigint NOT NULL DEFAULT 0,
    latency_n bigint NOT NULL DEFAULT 0,
    last_at bigint NOT NULL DEFAULT 0,
    PRIMARY KEY(scope, subject)
);

CREATE TABLE IF NOT EXISTS account_request_state (
    account_ref text PRIMARY KEY,
    account_name text NOT NULL,
    last_at timestamptz NOT NULL,
    last_log_id bigint NOT NULL,
    record jsonb NOT NULL
);
CREATE INDEX IF NOT EXISTS account_request_state_name_idx ON account_request_state(account_name);

-- Old stats.json can contain usage whose original logs were not retained.
-- These explicit immutable snapshot deltas preserve it without inventing
-- individual request events. One manifest is imported at most once.
CREATE TABLE IF NOT EXISTS usage_legacy_imports (
    manifest text PRIMARY KEY,
    imported_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS usage_legacy_baselines (
    manifest text NOT NULL REFERENCES usage_legacy_imports(manifest),
    scope text NOT NULL CHECK(scope IN ('minute','account_day')),
    bucket bigint NOT NULL,
    subject text NOT NULL,
    account_name text NOT NULL DEFAULT '',
    requests bigint NOT NULL,
    ok bigint NOT NULL,
    errors bigint NOT NULL,
    tokens bigint NOT NULL,
    input bigint NOT NULL,
    output bigint NOT NULL,
    cached bigint NOT NULL,
    latency bigint NOT NULL,
    latency_n bigint NOT NULL,
    PRIMARY KEY(manifest,scope,bucket,subject)
);
