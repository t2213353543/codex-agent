CREATE TABLE IF NOT EXISTS accounts (
    id text PRIMARY KEY,
    ordinal bigint GENERATED BY DEFAULT AS IDENTITY,
    display_name text NOT NULL CHECK (length(display_name) BETWEEN 1 AND 100),
    enabled boolean NOT NULL DEFAULT true,
    notes text NOT NULL DEFAULT '',
    tags text[] NOT NULL DEFAULT '{}',
    concurrency integer NOT NULL DEFAULT 1,
    priority integer NOT NULL DEFAULT 0,
    weight integer NOT NULL DEFAULT 1,
    quota bigint NOT NULL DEFAULT 0,
    window_days integer NOT NULL DEFAULT 30,
    window_start bigint NOT NULL DEFAULT 0,
    expires_at bigint NOT NULL DEFAULT 0,
    has_refresh_token boolean NOT NULL DEFAULT false,
    credential_status text NOT NULL DEFAULT 'unverified',
    last_checked_at bigint NOT NULL DEFAULT 0,
    last_error text NOT NULL DEFAULT '',
    created_at bigint NOT NULL,
    updated_at bigint NOT NULL,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0)
);
CREATE INDEX IF NOT EXISTS accounts_display_name_idx ON accounts(display_name);
CREATE INDEX IF NOT EXISTS accounts_created_id_idx ON accounts(created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS account_credentials (
    account_id text PRIMARY KEY REFERENCES accounts(id) ON DELETE CASCADE,
    credentials_cipher bytea NOT NULL,
    token_fingerprint bytea NOT NULL,
    expires_at bigint NOT NULL DEFAULT 0,
    credential_version bigint NOT NULL DEFAULT 1 CHECK (credential_version > 0),
    encryption_key_id text NOT NULL,
    updated_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS account_credentials_fingerprint_idx ON account_credentials(token_fingerprint);

CREATE TABLE IF NOT EXISTS account_groups (
    account_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    group_id text NOT NULL REFERENCES groups(id) ON DELETE CASCADE,
    PRIMARY KEY(account_id, group_id)
);
CREATE INDEX IF NOT EXISTS account_groups_reverse_idx ON account_groups(group_id, account_id);
CREATE TABLE IF NOT EXISTS account_proxies (
    account_id text NOT NULL REFERENCES accounts(id) ON DELETE CASCADE,
    proxy_id text NOT NULL REFERENCES proxies(id) ON DELETE CASCADE,
    position integer NOT NULL DEFAULT 0,
    PRIMARY KEY(account_id, proxy_id)
);
CREATE INDEX IF NOT EXISTS account_proxies_reverse_idx ON account_proxies(proxy_id, account_id);
